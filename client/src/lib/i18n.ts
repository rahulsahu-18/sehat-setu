export function translate(locale: Locale, message: string): string {
  if (locale === "en") return message;
  return additionalMessages[locale][message] || commonMessages[locale][message] || message;
}

export function translateStatus(locale: Locale, status: string): string {
  const normalized = status.replaceAll("_", " ");
  if (locale === "en") return normalized;
  const upper = normalized.toUpperCase();
  const languageNames: Record<string, string> = {
    ENGLISH: "English",
    HINDI: "Hindi",
    ODIA: "Odia",
  };
  const candidates = [upper, normalized, languageNames[upper]].filter(
    (value): value is string => Boolean(value),
  );
  for (const candidate of candidates) {
    const result =
      additionalMessages[locale][candidate] ??
      commonMessages[locale][candidate];
    if (result) return result;
  }
  return normalized;
}

export function localeTag(locale: Locale): string {
  return locale === "hi" ? "hi-IN" : locale === "or" ? "or-IN" : "en-IN";
}

export function useLocale(): Locale {
  const [locale, setCurrentLocale] = useState<Locale>(detectLocale);
  useEffect(() => {
    const update = () => setCurrentLocale(detectLocale());
    window.addEventListener("localechange", update);
    window.addEventListener("storage", update);
    return () => {
      window.removeEventListener("localechange", update);
      window.removeEventListener("storage", update);
    };
  }, []);
  return locale;
}

export function detectLocale(): Locale {
  if (typeof window === "undefined") return "en";
  const saved = window.localStorage.getItem(
    "sehatsetu-locale",
  ) as Locale | null;
  if (saved && locales.includes(saved)) return saved;
  const language = navigator.language.toLowerCase();
  if (language.startsWith("hi")) return "hi";
  if (language.startsWith("or")) return "or";
  return "en";
}
export function localeFromPath(): Locale {
  if (typeof window === "undefined") return "en";
  const value = window.location.pathname.split("/")[1] as Locale;
  return locales.includes(value) ? value : detectLocale();
}
export function setLocale(locale: Locale) {
  window.localStorage.setItem("sehatsetu-locale", locale);
  window.dispatchEvent(new Event("localechange"));
}

